"""Built-in struct-frame schemas, pre-generated into the language runtimes.

``sf_system.sf`` declares the system messages (heartbeat, ping, link tests, RPC envelope)
that travel in system frames. Its generated code is committed into
``boilerplate/<lang>/`` so the runtimes can use it without generating anything; this
module regenerates it::

    python -m struct_frame.builtin --write    # regenerate the committed files
    python -m struct_frame.builtin --check    # CI: fail when they are stale

The package name ``sf_system`` is reserved: application schemas cannot use it.
"""

import contextlib
import io
import os
import re
import shutil
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
SCHEMA = os.path.join(HERE, "sf_system.sf")
BOILERPLATE = os.path.join(os.path.dirname(HERE), "boilerplate")
PACKAGE = "sf_system"

# Generated file (relative to the language output) -> committed file (relative to
# boilerplate/). Rust gets a name that the generator's lib.rs scan of
# *.structframe.rs files does not pick up a second time.
_FILES = {
    "c": {"sf_system.structframe.h": "c/sf_system.structframe.h"},
    "cpp": {"sf_system.structframe.hpp": "cpp/sf_system.structframe.hpp"},
    "py": {"structframe/sf_system.py": "py/sf_system.py"},
    "ts": {"sf-system.structframe.ts": "ts/sf-system.structframe.ts"},
    "rust": {"sf_system.structframe.rs": "rust/sf_system.rs"},
}
_CSHARP_DIR = "SfSystem"
_CSHARP_TARGET = "csharp/Framework/SfSystem"
_CSHARP_SKIP = {"SdkInterface.cs"}

_VERSION_LINE = re.compile(r"(Generated by struct-frame) [0-9][^\s.*]*(?:\.[0-9A-Za-z+-]+)*\.?")

# System messages that may carry a raw tail after their fixed fields (padding, link-test
# data, RPC payloads). The hand-written Python and TypeScript runtimes repeat this list;
# tests/test_builtin_sync.py checks that they agree with it.
TAIL_MESSAGES = ("Ping", "Pong", "LinkTestData", "RpcRequest", "RpcResponse")

# Payload type and start byte of system frames.
SYSTEM_PAYLOAD_TYPE = 9
SYSTEM_START_BYTE = 0x70 + SYSTEM_PAYLOAD_TYPE

_TABLE_HEADER = """\
/* Automatically generated by `python -m struct_frame.builtin --write`; do not edit. */
/* System-message sizes and magic bytes for the frame readers. Only SF_SYSTEM_FRAME_*
 * names are defined here, so this header can sit next to any application schema. */
"""


def _system_table(packages):
    """[(name, id, fixed size, magic1, magic2, takes tail)] of the sf_system messages."""
    pkg = packages[PACKAGE]
    unknown = set(TAIL_MESSAGES) - set(pkg.messages)
    if unknown:
        raise RuntimeError(f"TAIL_MESSAGES names unknown messages: {sorted(unknown)}")
    rows = []
    for name, msg in sorted(pkg.messages.items(), key=lambda item: item[1].id):
        if msg.variable or msg.base_size != msg.size:
            raise RuntimeError(f"system message {name} must be fixed-size without extensions")
        rows.append((name, msg.id, msg.size, msg.magic_bytes[0], msg.magic_bytes[1], name in TAIL_MESSAGES))
    return rows


def _max_tail(packages):
    return int(packages[PACKAGE].consts["MAX_TAIL"].value)


def _c_table(rows, max_tail):
    max_payload = max(size + (max_tail if tail else 0) for _n, _i, size, _a, _b, tail in rows)
    out = [_TABLE_HEADER, "#pragma once\n\n#include \"frame_base.h\"\n\n#ifdef __cplusplus\nextern \"C\" {\n#endif\n\n"]
    out.append(f"#define SF_SYSTEM_FRAME_PAYLOAD_TYPE {SYSTEM_PAYLOAD_TYPE}\n")
    out.append(f"#define SF_SYSTEM_FRAME_START_BYTE 0x{SYSTEM_START_BYTE:02X}\n")
    out.append(f"/* Largest tail after a system message's fixed fields. */\n#define SF_SYSTEM_FRAME_MAX_TAIL {max_tail}\n")
    out.append(f"/* Largest system-frame payload (fixed fields plus tail). */\n#define SF_SYSTEM_FRAME_MAX_PAYLOAD {max_payload}\n\n")
    out.append("/* Size limits of a system message: min_size is the fixed size, size also allows a\n"
               " * tail for the messages that take one, base_size == size (no extension split). */\n")
    out.append("static inline bool sf_system_frame_message_info(uint16_t msg_id, message_info_t* info) {\n")
    out.append("    size_t fixed;\n    size_t tail;\n    uint8_t magic1;\n    uint8_t magic2;\n")
    out.append("    switch (msg_id) {\n")
    for name, msg_id, size, m1, m2, tail in rows:
        out.append(f"        case 0x{msg_id:02X}: fixed = {size}; tail = {max_tail if tail else 0}; "
                   f"magic1 = {m1}; magic2 = {m2}; break; /* {name} */\n")
    out.append("        default: return false;\n    }\n")
    out.append("    info->size = fixed + tail;\n    info->base_size = fixed + tail;\n    info->min_size = fixed;\n")
    out.append("    info->magic1 = magic1;\n    info->magic2 = magic2;\n    return true;\n}\n\n")
    out.append("#ifdef __cplusplus\n}\n#endif\n")
    return "".join(out)


def _cpp_table(rows, max_tail):
    max_payload = max(size + (max_tail if tail else 0) for _n, _i, size, _a, _b, tail in rows)
    out = [_TABLE_HEADER.replace("SF_SYSTEM_FRAME_*\n * names", "structframe::system_frames\n * names"),
           "#pragma once\n\n#include <cstddef>\n#include <cstdint>\n\n#include \"frame_base.hpp\"\n\n",
           "namespace structframe {\nnamespace system_frames {\n\n"]
    out.append(f"inline constexpr uint8_t PAYLOAD_TYPE = {SYSTEM_PAYLOAD_TYPE};\n")
    out.append(f"inline constexpr uint8_t START_BYTE = 0x{SYSTEM_START_BYTE:02X};\n")
    out.append(f"// Largest tail after a system message's fixed fields.\ninline constexpr size_t MAX_TAIL = {max_tail};\n")
    out.append(f"// Largest system-frame payload (fixed fields plus tail).\ninline constexpr size_t MAX_PAYLOAD = {max_payload};\n\n")
    out.append("// Size limits of a system message: min_size is the fixed size, size also allows a tail\n"
               "// for the messages that take one, base_size == size (no extension split).\n")
    out.append("inline MessageInfo message_info(uint16_t msg_id) {\n    switch (msg_id) {\n")
    for name, msg_id, size, m1, m2, tail in rows:
        total = size + (max_tail if tail else 0)
        out.append(f"        case 0x{msg_id:02X}: return MessageInfo({total}, {m1}, {m2}, {total}, {size});  // {name}\n")
    out.append("        default: return MessageInfo();\n    }\n}\n\n")
    out.append("}  // namespace system_frames\n}  // namespace structframe\n")
    return "".join(out)


def _normalize(text):
    """Make committed files independent of the generator version."""
    text = text.replace("\r\n", "\n")
    return _VERSION_LINE.sub(r"\1 (built-in schema)", text)


def generate_files():
    """{boilerplate-relative path: content} of every built-in generated file."""
    from struct_frame import generate as gen
    files = {}
    with tempfile.TemporaryDirectory(prefix="sf_builtin_") as tmp:
        out, err = io.StringIO(), io.StringIO()
        previous = gen.ALLOW_RESERVED_PACKAGES
        previous_root = gen._BOILERPLATE_ROOT
        gen.ALLOW_RESERVED_PACKAGES = True
        # The generator copies the runtime next to its output, and the committed built-in
        # files live in the runtime: copied over the fresh output they would replace it with
        # the previous generation. Generate against a runtime copy without them.
        runtime = os.path.join(tmp, "runtime")
        builtin_names = {os.path.basename(dst) for mapping in _FILES.values() for dst in mapping.values()}
        builtin_names |= {"sf-system.structframe.js", _CSHARP_DIR, "__pycache__", "bin", "obj"}
        shutil.copytree(BOILERPLATE, runtime, ignore=shutil.ignore_patterns(*builtin_names))
        gen._BOILERPLATE_ROOT = runtime
        try:
            with contextlib.redirect_stdout(out), contextlib.redirect_stderr(err):
                status = gen.main([SCHEMA, "--lang", "c,cpp,py,ts,csharp,rust", "--out", tmp,
                                   "--catalog_path", tmp, "--force", "-q"])
        finally:
            gen.ALLOW_RESERVED_PACKAGES = previous
            gen._BOILERPLATE_ROOT = previous_root
        if status:
            raise RuntimeError("generating the built-in schema failed:\n" + out.getvalue() + err.getvalue())
        for lang, mapping in _FILES.items():
            for src, dst in mapping.items():
                with open(os.path.join(tmp, lang, src), encoding="utf-8") as f:
                    files[dst] = _normalize(f.read())
        gen.reset_parse_state()
        try:
            with contextlib.redirect_stdout(out), contextlib.redirect_stderr(err):
                gen.ALLOW_RESERVED_PACKAGES = True
                ok = gen.parseFile(SCHEMA) and gen.validate_packages()
            if not ok:
                raise RuntimeError("parsing the built-in schema failed:\n" + out.getvalue() + err.getvalue())
            rows = _system_table(gen.packages)
            max_tail = _max_tail(gen.packages)
        finally:
            gen.ALLOW_RESERVED_PACKAGES = previous
            gen.reset_parse_state()
        files["c/sf_system_info.h"] = _c_table(rows, max_tail)
        files["cpp/sf_system_info.hpp"] = _cpp_table(rows, max_tail)
        cs_root = os.path.join(tmp, "csharp", _CSHARP_DIR)
        for dirpath, _dirs, names in os.walk(cs_root):
            for name in names:
                if name in _CSHARP_SKIP or not name.endswith(".cs"):
                    continue
                full = os.path.join(dirpath, name)
                rel = os.path.relpath(full, cs_root).replace(os.sep, "/")
                with open(full, encoding="utf-8") as f:
                    files[f"{_CSHARP_TARGET}/{rel}"] = _normalize(f.read())
    return dict(sorted(files.items()))


def committed_files():
    """{path: content} of the built-in files currently in boilerplate/."""
    paths = [dst for mapping in _FILES.values() for dst in mapping.values()]
    paths += ["c/sf_system_info.h", "cpp/sf_system_info.hpp"]
    cs_dir = os.path.join(BOILERPLATE, *_CSHARP_TARGET.split("/"))
    if os.path.isdir(cs_dir):
        for dirpath, _dirs, names in os.walk(cs_dir):
            for name in names:
                rel = os.path.relpath(os.path.join(dirpath, name), BOILERPLATE).replace(os.sep, "/")
                paths.append(rel)
    files = {}
    for rel in paths:
        full = os.path.join(BOILERPLATE, *rel.split("/"))
        if os.path.exists(full):
            with open(full, encoding="utf-8") as f:
                files[rel] = f.read().replace("\r\n", "\n")
    return dict(sorted(files.items()))


def write():
    files = generate_files()
    cs_dir = os.path.join(BOILERPLATE, *_CSHARP_TARGET.split("/"))
    for rel in committed_files():
        if rel not in files and rel.startswith(_CSHARP_TARGET + "/"):
            os.remove(os.path.join(BOILERPLATE, *rel.split("/")))
    for rel, text in files.items():
        full = os.path.join(BOILERPLATE, *rel.split("/"))
        os.makedirs(os.path.dirname(full), exist_ok=True)
        with open(full, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
    return sorted(files)


def stale():
    """Paths whose committed content differs from a fresh generation."""
    want = generate_files()
    have = committed_files()
    return sorted(p for p in set(want) | set(have) if want.get(p) != have.get(p))
