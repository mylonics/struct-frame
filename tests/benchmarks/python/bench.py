#!/usr/bin/env python3
"""Python benchmark that runs the real struct-frame runtime and generated code.

Messages come from tests/benchmarks/schema/bench.sf, generated by run_all.py into
--gen-dir. Encode goes through BufferWriter and decode through BufferReader plus the
generated deserialize, so the numbers include the framing, checksum and codec cost.
"""
import argparse, json, os, platform, socket, sys, time
from datetime import datetime, timezone
from pathlib import Path

# (scenario name, profile config attribute, message class name, uses sequence fields)
SCENARIOS = [
    ("standard", "PROFILE_STANDARD_CONFIG", "Small"),
    ("bulk", "PROFILE_BULK_CONFIG", "Large"),
    ("network", "PROFILE_NETWORK_CONFIG", "Medium"),
    ("sensor", "PROFILE_SENSOR_CONFIG", "Small"),
    ("ipc", "PROFILE_IPC_CONFIG", "Small"),
]
BATCH = 64          # operations timed together; per-op latency is batch time / BATCH
WARMUP_BATCHES = 20


def pct(values, q):
    values.sort()
    return values[min(len(values) - 1, int((len(values) - 1) * q))]


def run_case(fp, gen, scenario, op, iterations):
    name, cfg_attr, msg_name = scenario
    cfg = getattr(fp, cfg_attr)
    msg_cls = getattr(gen, msg_name)
    msg = msg_cls(data=[(i * 31) & 0xFF for i in range(msg_cls.MAX_SIZE)])
    frames = []
    for seq in range(8):
        w = fp.BufferWriter(cfg, 2048)
        w.write(msg, seq=seq, sys_id=1, comp_id=42)
        frames.append(w.data())
    writer = fp.BufferWriter(cfg, 2048)

    def encode_once(i):
        writer.reset()
        return writer.write(msg, seq=i & 0xFF, sys_id=1, comp_id=42)

    def decode_once(i):
        info = fp.BufferReader(cfg, frames[i & 7], gen.get_message_info).next()
        if not info.valid:
            raise RuntimeError("decode failed")
        msg_cls.deserialize(info)
        return len(frames[i & 7])

    fn = encode_once if op == "encode" else decode_once
    for i in range(WARMUP_BATCHES * BATCH):
        fn(i)

    batches = max(1, iterations // BATCH)
    lat = []
    total_bytes = 0
    start = time.perf_counter_ns()
    for b in range(batches):
        t0 = time.perf_counter_ns()
        for i in range(BATCH):
            total_bytes += fn(b * BATCH + i)
        lat.append((time.perf_counter_ns() - t0) // BATCH)
    duration = max((time.perf_counter_ns() - start) / 1e9, 1e-9)
    count = batches * BATCH
    return {"name": f"{name}_{op}", "profile": name, "operation": op, "msg_count": count,
            "bytes_total": total_bytes, "duration_s": duration, "msg_per_sec": count / duration,
            "mb_per_sec": total_bytes / duration / 1_000_000,
            "latency_ns": {"p50": pct(lat, .50), "p95": pct(lat, .95), "p99": pct(lat, .99), "max": max(lat)}}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--iterations", type=int, default=int(os.getenv("BENCH_ITERATIONS", "50000")))
    ap.add_argument("--output", default="tests/benchmarks/results/python.json")
    ap.add_argument("--gen-dir", default="tests/benchmarks/generated/py")
    args = ap.parse_args()
    sys.path.insert(0, str(Path(args.gen_dir).resolve()))
    import frame_profiles as fp
    from struct_frame.generated import bench as gen

    scenarios = [run_case(fp, gen, s, op, args.iterations) for s in SCENARIOS for op in ("encode", "decode")]
    result = {"schema_version": "1", "language": "python", "runner_version": "tier-d-2-generated",
              "timestamp": datetime.now(timezone.utc).isoformat().replace('+00:00', 'Z'),
              "host": {"os": platform.system(), "arch": platform.machine(),
                       "cpu": platform.processor() or socket.gethostname()},
              "scenarios": scenarios}
    Path(args.output).parent.mkdir(parents=True, exist_ok=True)
    Path(args.output).write_text(json.dumps(result, indent=2) + "\n")


if __name__ == "__main__":
    main()
